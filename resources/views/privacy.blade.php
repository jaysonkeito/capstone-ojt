    <h1>Privacy Policy — OJT Tracker</h1>
    <p class="meta">Negros Oriental State University — College of Arts and Sciences, MIS Office. Last updated: October 2026.</p>

    <div class="card">
        <h2>What this system is</h2>
        <p>OJT Tracker records On-the-Job Training attendance and documentation for student
        interns of NORSU CAS. It is operated by the University's Management Information System
        Office for official internship records.</p>

        <h2>Data we process</h2>
        <ul>
            <li><strong>Identity and academic data</strong> from the University registrar's
            official list of interns: student ID, name, program, year level, and section.</li>
            <li><strong>Attendance records</strong> — the time in/out scans recorded at the
            office kiosk scanner, plus corrected or manual entries reviewed by supervisors.</li>
            <li><strong>Duty journals</strong> — the journal entries and duty photos you
            upload, visible to your coordinators and supervisors for review.</li>
            <li><strong>Personal information you enter</strong> — contact details, addresses,
            and family background for the school's Personal Information sheet, kept private to
            you and the OJT office.</li>
            <li><strong>Device registration tokens</strong> — when push notifications are
            enabled, your phone's Firebase token is stored so the app can notify you. Firebase
            (Google) delivers these notifications on the University's behalf.</li>
        </ul>

        <h2>What we do not do</h2>
        <ul>
            <li>We do not sell or share your data with anyone outside the University.</li>
            <li>We do not use your data for advertising or tracking.</li>
            <li>The Android app requests only the notification permission (and the photo
            picker when you attach a duty photo).</li>
        </ul>

        <h2>Retention and deletion</h2>
        <p>Internship records are retained per University policy. You may request removal of
        your account and personal data through the MIS Office; attendance records form part of
        your official academic requirements and are retained accordingly.</p>

        <h2>Contact</h2>
        <p>Questions or data requests: MIS Office, NORSU — Bais City Campus, or via the OJT
        Coordinator.</p>
